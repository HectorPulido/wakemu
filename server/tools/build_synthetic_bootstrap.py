"""Build the public Wakemu bootstrap from typed, identity-free native defaults.

This intentionally defines a new fixture authority. It never reads a capture,
player database, account credentials, client files, or historical packet bodies.
"""
import argparse
import base64
import gzip
import hashlib
import json
from pathlib import Path
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

POLICY = "wakemu-synthetic-bootstrap-v1"
ACCOUNT_ID = 83668792
CHARACTER_ID = 2409354
ACCOUNT_DISPATCH_ID = 83668792
# These are existing public protocol template constants, not imported accounts.
# Reusing them keeps static native transport/actor prototypes compatible with
# the same strict identity adapter after the synthetic template is installed.
NAME = "Wakemu"


def build(defaults):
    from synthetic_bootstrap_auth import auth472, auth457, realms453
    from synthetic_bootstrap_entities import build_entities
    from synthetic_bootstrap_world import world_frames

    entities, layouts = build_entities(defaults, ACCOUNT_ID, CHARACTER_ID, NAME)
    records = [dict(direction="out", opcode=0, body_base64="") for _ in range(132)]
    frames = world_frames(entities, ACCOUNT_ID, CHARACTER_ID, NAME)
    # Authentication frames are standalone fixture lookups. Slots outside the
    # replay ranges cannot accidentally replay a login response during selection.
    frames.update(
        {
            1: (453, realms453()),
            2: (472, auth472(ACCOUNT_ID, ACCOUNT_DISPATCH_ID, NAME)),
            3: (457, auth457(ACCOUNT_ID, NAME)),
        }
    )
    for index, (opcode, body) in frames.items():
        if type(index) is not int or not 0 <= index < 132 or index == 44:
            raise ValueError("Invalid synthetic replay slot")
        if type(opcode) is not int or not isinstance(body, bytes):
            raise ValueError("Invalid synthetic packet")
        records[index] = dict(
            direction="in",
            opcode=opcode,
            body_base64=base64.b64encode(body).decode("ascii"),
        )
    name = NAME.encode("utf-8")
    records[44] = dict(
        direction="out",
        opcode=23664,
        body_base64=base64.b64encode(
            struct.pack(">qI", CHARACTER_ID, len(name)) + name
        ).decode("ascii"),
    )
    records[0]["synthetic_template"] = dict(
        policy=POLICY,
        account_id=ACCOUNT_ID,
        character_id=CHARACTER_ID,
        account_dispatch_id=ACCOUNT_DISPATCH_ID,
        name=NAME,
        layouts=layouts,
    )
    return records


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--defaults",
        required=True,
        type=Path,
        help="Fresh native serializer defaults generated by the source oracle",
    )
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    records = build(json.loads(args.defaults.read_text()))
    raw = b"".join(
        (
            json.dumps(row, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
            + "\n"
        ).encode()
        for row in records
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    body = (
        gzip.compress(raw, compresslevel=9, mtime=0)
        if args.output.suffix == ".gz"
        else raw
    )
    args.output.write_bytes(body)
    print(
        json.dumps(
            dict(
                policy=POLICY,
                frame_count=len(records),
                source_bytes=len(raw),
                source_sha256=hashlib.sha256(raw).hexdigest(),
                artifact_bytes=len(body),
                artifact_sha256=hashlib.sha256(body).hexdigest(),
            )
        )
    )


if __name__ == "__main__":
    main()

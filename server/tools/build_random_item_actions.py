#!/usr/bin/env python3
"""Regenerate migration 200 from the frozen original random-box action tables."""
import argparse
import collections
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / "protocol/native-random-item-actions.json"
MIGRATION = ROOT / "migrations/200_native_random_item_actions.sql"


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def literal(value):
    if value is None:
        return "NULL"
    if type(value) is bool:
        return "true" if value else "false"
    if type(value) is int:
        return str(value)
    return (
        "E'"
        + value.replace("\\", "\\\\")
        .replace("'", "''")
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        + "'"
    )


def generate(document):
    actions, tables = document["actions"], document["tables"]
    if (
        len(actions) != 436
        or len(tables) != 1144
        or sum(a["available"] for a in actions) != 390
    ):
        raise ValueError("Original random action coverage changed")
    if (
        len({a["item_ref"] for a in actions}) != 436
        or len({t["d"] for t in tables}) != 1144
    ):
        raise ValueError("Duplicate native random action or table")
    digest = hashlib.sha256(canonical(document).encode()).hexdigest()
    sql = """-- Generated by server/tools/build_random_item_actions.py.
-- Draw policy is documented in native-random-item-actions.json; raw native weights are preserved.
CREATE TABLE native_random_item_actions (
    item_ref integer PRIMARY KEY CHECK (item_ref > 0),
    action_id integer NOT NULL CHECK (action_id > 0),
    root_table integer NOT NULL CHECK (root_table > 0),
    criterion text NOT NULL,
    action_parameters jsonb NOT NULL CHECK (jsonb_typeof(action_parameters)='array'),
    available boolean NOT NULL,
    unavailable_reasons jsonb NOT NULL CHECK (jsonb_typeof(unavailable_reasons)='array'),
    source_sha256 text NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$')
);
CREATE TABLE native_random_item_tables (
    reference integer PRIMARY KEY CHECK (reference > 0),
    payload jsonb NOT NULL CHECK (jsonb_typeof(payload)='object'),
    source_sha256 text NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$')
);
-- gen_random_uuid is a core PostgreSQL cryptographic UUID source. Never publish this entropy.
CREATE TABLE random_item_entropy (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    secret bytea NOT NULL CHECK (octet_length(secret)=32)
);
INSERT INTO random_item_entropy(singleton,secret)
VALUES(true,decode(replace(gen_random_uuid()::text || gen_random_uuid()::text,'-',''),'hex'));
CREATE TABLE random_item_use_counters (
    source_uid bigint PRIMARY KEY REFERENCES inventory_items(uid) ON DELETE CASCADE,
    next_use bigint NOT NULL DEFAULT 0 CHECK (next_use >= 0)
);
INSERT INTO native_random_item_actions
(item_ref,action_id,root_table,criterion,action_parameters,available,unavailable_reasons,source_sha256) VALUES
"""
    values = []
    for action in actions:
        row = [
            action["item_ref"],
            action["action_id"],
            action["root_table"],
            action["criterion"],
            canonical(action["action_parameters"]),
            action["available"],
            canonical(action["unavailable_reasons"]),
            digest,
        ]
        values.append("(" + ",".join(literal(value) for value in row) + ")")
    sql += (
        ",\n".join(values)
        + ";\nINSERT INTO native_random_item_tables(reference,payload,source_sha256) VALUES\n"
    )
    sql += (
        ",\n".join(
            "(" + ",".join(map(literal, (table["d"], canonical(table), digest))) + ")"
            for table in tables
        )
        + ";\n"
    )
    return sql, digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sql, digest = generate(json.loads(DOCUMENT.read_text()))
    if args.check:
        if MIGRATION.read_text() != sql:
            raise SystemExit(
                "Random item migration differs from descriptor regeneration"
            )
    else:
        MIGRATION.write_text(sql)
    print(f"436 boxes;390 qualified;1144 native tables;source_sha256={digest}")


if __name__ == "__main__":
    main()

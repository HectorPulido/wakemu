#!/usr/bin/env python3
"""Generate the additive native random-item USE admission snapshot."""
import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / "protocol/native-random-item-use-criteria.json"
BASE_DOCUMENT = ROOT / "protocol/native-random-item-actions.json"
MIGRATION = ROOT / "migrations/227_native_random_item_use_criteria.sql"


def generate(document, base_document):
    rows = document["actions"]
    identities = {(row["item_ref"], row["action_id"]) for row in rows}
    expected = {(row["item_ref"], row["action_id"]) for row in base_document["actions"]}
    if len(rows) != 436 or len(identities) != len(rows) or identities != expected:
        raise ValueError(
            "Native random-item USE coverage differs from the action snapshot"
        )
    if any(not isinstance(row["use_criterion"], str) for row in rows):
        raise ValueError("Invalid native random-item USE criterion")
    digest = hashlib.sha256(
        json.dumps(
            document, sort_keys=True, separators=(",", ":"), ensure_ascii=False
        ).encode()
    ).hexdigest()
    values = []
    for row in sorted(rows, key=lambda entry: entry["item_ref"]):
        criterion = row["use_criterion"].replace("'", "''")
        values.append(f"({row['item_ref']},{row['action_id']},'{criterion}')")
    sql = (
        f"""-- Generated by server/tools/build_random_item_use_criteria.py.
-- Original USE snapshot SHA256: {digest}
-- Preserve the separate native action criterion and immutable migration 200.
ALTER TABLE native_random_item_actions
    ADD COLUMN use_criterion text NOT NULL DEFAULT '';

DO $native_random_use$
DECLARE
    updated_count integer;
BEGIN
    UPDATE native_random_item_actions AS action
    SET use_criterion = native.use_criterion
    FROM (VALUES
"""
        + ",\n".join(values)
        + """
    ) AS native(item_ref,action_id,use_criterion)
    WHERE action.item_ref=native.item_ref AND action.action_id=native.action_id;
    GET DIAGNOSTICS updated_count = ROW_COUNT;
    IF updated_count <> 436 THEN
        RAISE EXCEPTION 'Native random-item USE action identity mismatch';
    END IF;
END
$native_random_use$;
"""
    )
    return sql, digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sql, digest = generate(
        json.loads(DOCUMENT.read_text()), json.loads(BASE_DOCUMENT.read_text())
    )
    if args.check:
        if MIGRATION.read_text() != sql:
            raise SystemExit(
                "Random-item USE migration differs from the native snapshot"
            )
    else:
        MIGRATION.write_text(sql)
    print(f"436 native random-item USE criteria; source_sha256={digest}")


if __name__ == "__main__":
    main()

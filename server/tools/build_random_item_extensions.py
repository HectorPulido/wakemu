#!/usr/bin/env python3
"""Qualify existing native Rift box tables without editing migration200."""
import argparse
import hashlib
import json
from pathlib import Path

from build_random_item_actions import canonical, literal

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "protocol/native-random-item-actions.json"
DOCUMENT = ROOT / "protocol/native-random-item-extensions.json"
MIGRATION = ROOT / "migrations/214_native_random_item_extensions.sql"
BASE_SHA256 = "1ee0fa5fc731932c084570d5f653a26cdacd964d5424270bb38c398d48dc1b97"


def build():
    base = json.loads(BASE.read_text())
    if hashlib.sha256(canonical(base).encode()).hexdigest() != BASE_SHA256:
        raise ValueError("Original random-box source changed")
    actions = [
        a
        for a in base["actions"]
        if a["unavailable_reasons"] == ["criteria", "table_type"]
    ]
    if len(actions) != 10:
        raise ValueError("Native Rift box qualification changed")
    tables = {table["d"]: table for table in base["tables"]}
    reached, criteria = set(), set()

    def visit(reference, path=()):
        if reference in path:
            raise ValueError("Cyclic native Rift table")
        table = tables[reference]
        if table["czg"] not in (1, 3):
            raise ValueError("Unqualified native table kind")
        reached.add(reference)
        for entry in table["gBN"]:
            if entry["cmY"] == 0 or entry["cqz"] == 0:
                continue
            if (entry["bfh"], entry["czl"], entry["csE"]) != (1, 0, 1) or entry["gBO"]:
                raise ValueError("Unqualified native roll conditions")
            if entry["czk"]:
                criteria.add(entry["czk"])
            if entry["cqA"]:
                visit(entry["aAi"], path + (reference,))

    for action in actions:
        if action["action_parameters"][-1].lower() != "false":
            raise ValueError("Rift extension unexpectedly enables blind-box UI")
        visit(action["root_table"])
    if len(criteria) != 2 or not all(
        text.startswith("GetStateLevel(6836) >= ") for text in criteria
    ):
        raise ValueError("Native Rift criterion grammar changed")
    policy = {
        "kind": "native-display-relative-weighted-types1-3-v1",
        "base_source_sha256": BASE_SHA256,
        "table_types": [1, 3],
        "criteria": sorted(criteria),
        "criterion_policy": "Filter ineligible entries before weighted selection; no invented Rift state6836 or wave conversion.",
        "draw_policy": "Extend the existing explicit server weighted draw policy to native type3. Actual original brq.d normalizes its positive entry weights exactly as type1; the original server draw engine is absent.",
        "neo_authority": "settings.dungeon_server_mode.is_neo_server",
    }
    document = {
        "schema_version": 1,
        "policy": policy,
        "actions": [
            {key: action[key] for key in ("item_ref", "action_id", "root_table")}
            for action in actions
        ],
        "reachable_tables": sorted(reached),
        "qualification": "All table and item definitions already present in immutable migration200; only table kind3 and two supported entry criteria are newly qualified.",
    }
    digest = hashlib.sha256(canonical(document).encode()).hexdigest()
    sql = """-- Generated by build_random_item_extensions.py; migration200 remains immutable.
CREATE TABLE native_random_item_extensions (
    item_ref integer PRIMARY KEY REFERENCES native_random_item_actions(item_ref),
    policy jsonb NOT NULL CHECK (jsonb_typeof(policy)='object'),
    source_sha256 text NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$')
);
INSERT INTO native_random_item_extensions(item_ref,policy,source_sha256) VALUES
"""
    sql += (
        ",\n".join(
            "("
            + ",".join(map(literal, (action["item_ref"], canonical(policy), digest)))
            + ")"
            for action in actions
        )
        + ";\n"
    )
    refs = ",".join(str(action["item_ref"]) for action in actions)
    sql += f"UPDATE native_random_item_actions SET available=true,unavailable_reasons='[]'::jsonb WHERE item_ref IN ({refs}) AND source_sha256='{BASE_SHA256}' AND unavailable_reasons='[\"criteria\",\"table_type\"]'::jsonb;\n"
    sql += "DO $$ BEGIN IF (SELECT count(*) FROM native_random_item_actions a JOIN native_random_item_extensions x USING(item_ref) WHERE a.available) <> 10 THEN RAISE EXCEPTION 'Native Rift random extension qualification mismatch'; END IF; END $$;\n"
    return document, sql, digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document, sql, digest = build()
    rendered = json.dumps(document, ensure_ascii=False, indent=2) + "\n"
    if args.check:
        if DOCUMENT.read_text() != rendered or MIGRATION.read_text() != sql:
            raise SystemExit("Native Rift random extension artifacts differ")
    else:
        DOCUMENT.write_text(rendered)
        MIGRATION.write_text(sql)
    print(f"10 additional boxes;400/436 available;source_sha256={digest}")


if __name__ == "__main__":
    main()

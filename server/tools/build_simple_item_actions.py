#!/usr/bin/env python3
"""Freeze native fixed grants, fragment merges, kamas and XP actions.

The optional import inputs are offline exports from original aLO/aLQ rows, parsed
by bHM/w. No database, client or live server is accessed. By default regenerate
migration 197 from the checked-in descriptor document.
"""
from __future__ import annotations

import argparse
import collections
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / "protocol/native-simple-item-actions.json"
MIGRATION = ROOT / "migrations/197_native_simple_item_actions.sql"
EXPECTED_COUNTS = {"bHI": 471, "bHS": 106, "bHy": 48, "bHK": 8}


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def build_rows(rewards, utilities, item_refs):
    actions = list(rewards["actions"]) + list(utilities["utility_actions"])
    rows = []
    for action in actions:
        native_class = action.get("native_class", action.get("class"))
        if native_class not in EXPECTED_COUNTS:
            continue
        parameters = action["parameters"]
        row = dict(
            item_ref=int(action["item_ref"]),
            action_id=int(action["action_id"]),
            native_class=native_class,
            output_ref=None,
            output_quantity=None,
            required_quantity=1,
            amount=None,
            criterion=action["criteria"],
            action_parameters=parameters,
            available=True,
            unavailable_reason="",
        )
        if native_class == "bHI":
            if len(parameters) not in (2, 3):
                raise ValueError("Unexpected fixed grant parameter count")
            row.update(
                output_ref=int(parameters[0]), output_quantity=int(parameters[1])
            )
        elif native_class == "bHS":
            if len(parameters) != 2:
                raise ValueError("Unexpected merge parameter count")
            row.update(
                required_quantity=int(parameters[0]),
                output_ref=int(parameters[1]),
                output_quantity=1,
            )
        else:
            if len(parameters) != 1:
                raise ValueError("Unexpected amount parameter count")
            row["amount"] = int(parameters[0])
        if row["output_ref"] is not None and row["output_ref"] not in item_refs:
            row.update(
                available=False,
                unavailable_reason=f"Native output item {row['output_ref']} is absent from the installed item catalog",
            )
        if row["required_quantity"] == 0:
            row.update(
                available=False,
                unavailable_reason="Native merge quantity is zero; no authoritative positive consumption rule",
            )
        rows.append(row)
    rows.sort(key=lambda row: row["item_ref"])
    validate(rows)
    return rows


def validate(rows):
    if (
        dict(collections.Counter(row["native_class"] for row in rows))
        != EXPECTED_COUNTS
    ):
        raise ValueError("Native action family coverage changed")
    if len({row["item_ref"] for row in rows}) != len(rows):
        raise ValueError("Duplicate native action item")
    for row in rows:
        if min(row["item_ref"], row["action_id"]) <= 0 or row["required_quantity"] < 0:
            raise ValueError("Invalid native action identity or quantity")
        if row["native_class"] in ("bHI", "bHS"):
            if (
                row["output_ref"] <= 0
                or not 1 <= row["output_quantity"] <= 32767
                or row["amount"] is not None
            ):
                raise ValueError("Invalid item grant")
        elif (
            row["output_ref"] is not None
            or row["output_quantity"] is not None
            or row["amount"] <= 0
        ):
            raise ValueError("Invalid native amount grant")
        if not isinstance(row["criterion"], str) or not isinstance(
            row["action_parameters"], list
        ):
            raise ValueError("Missing original action evidence")
    unavailable = {row["item_ref"] for row in rows if not row["available"]}
    if unavailable != {15931, 16864, 16865, 16866, 16867}:
        raise ValueError("Unexpected native orphan package coverage")


def sql_literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return (
        "E'"
        + value.replace("\\", "\\\\")
        .replace("'", "''")
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        + "'"
    )


def migration(rows):
    validate(rows)
    digest = hashlib.sha256(canonical(rows).encode()).hexdigest()
    sql = """-- Generated by server/tools/build_simple_item_actions.py from original native actions.
CREATE TABLE native_simple_item_actions (
    item_ref integer PRIMARY KEY CHECK (item_ref > 0),
    action_id integer NOT NULL CHECK (action_id > 0),
    native_class text NOT NULL CHECK (native_class IN ('bHI','bHS','bHy','bHK')),
    output_ref integer CHECK (output_ref > 0),
    output_quantity integer CHECK (output_quantity BETWEEN 1 AND 32767),
    required_quantity integer NOT NULL CHECK (required_quantity BETWEEN 0 AND 32767),
    amount bigint CHECK (amount > 0),
    criterion text NOT NULL,
    action_parameters jsonb NOT NULL CHECK (jsonb_typeof(action_parameters) = 'array'),
    available boolean NOT NULL,
    unavailable_reason text NOT NULL,
    source_sha256 text NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK ((native_class IN ('bHI','bHS') AND output_ref IS NOT NULL AND output_quantity IS NOT NULL AND amount IS NULL)
        OR (native_class IN ('bHy','bHK') AND output_ref IS NULL AND output_quantity IS NULL AND amount IS NOT NULL)),
    CHECK ((available AND unavailable_reason = '' AND required_quantity > 0) OR (NOT available AND unavailable_reason <> ''))
);
INSERT INTO native_simple_item_actions
(item_ref,action_id,native_class,output_ref,output_quantity,required_quantity,amount,criterion,action_parameters,available,unavailable_reason,source_sha256) VALUES
"""
    columns = (
        "item_ref",
        "action_id",
        "native_class",
        "output_ref",
        "output_quantity",
        "required_quantity",
        "amount",
        "criterion",
        "action_parameters",
        "available",
        "unavailable_reason",
    )
    values = []
    for row in rows:
        values.append(
            "("
            + ",".join(
                sql_literal(
                    canonical(row[key]) if key == "action_parameters" else row[key]
                )
                for key in columns
            )
            + ","
            + sql_literal(digest)
            + ")"
        )
    return sql + ",\n".join(values) + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rewards", type=Path)
    parser.add_argument("--utilities", type=Path)
    parser.add_argument(
        "--items", type=Path, help="Complete native item CSV with reference column"
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if any((args.rewards, args.utilities, args.items)):
        if not all((args.rewards, args.utilities, args.items)):
            parser.error("All three native import inputs are required")
        with args.items.open() as handle:
            refs = {int(row["reference"]) for row in csv.DictReader(handle)}
        rows = build_rows(
            json.loads(args.rewards.read_text()),
            json.loads(args.utilities.read_text()),
            refs,
        )
    else:
        rows = json.loads(DOCUMENT.read_text())["actions"]
    document = (
        json.dumps(
            {
                "schema_version": 1,
                "source": "Original installed aLO/aLQ action rows parsed through bHM/w",
                "actions": rows,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n"
    )
    generated = migration(rows)
    if args.check:
        if DOCUMENT.read_text() != document or MIGRATION.read_text() != generated:
            raise SystemExit("Native simple action artifacts differ from regeneration")
    else:
        DOCUMENT.write_text(document)
        MIGRATION.write_text(generated)
    print(
        f"633 actions; 628 available; 4 orphan packages and 1 zero-input merge; source_sha256={hashlib.sha256(canonical(rows).encode()).hexdigest()}"
    )


if __name__ == "__main__":
    main()

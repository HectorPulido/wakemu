INSERT INTO shop_categories(key,name,sort_order)
    SELECT DISTINCT category,category,100 FROM shop_articles
    ON CONFLICT(key) DO NOTHING;
ALTER TABLE shop_articles ADD CONSTRAINT shop_article_category_fk
    FOREIGN KEY(category) REFERENCES shop_categories(key)
    ON UPDATE CASCADE ON DELETE RESTRICT;

-- PostgreSQL is the final persistence contract. No SQLite dialect adapter.
CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL,
    username_key text NOT NULL UNIQUE,
    salt bytea NOT NULL CHECK (octet_length(salt) = 16),
    password_hash bytea NOT NULL,
    is_admin boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(username) BETWEEN 3 AND 32),
    CHECK (length(username_key) BETWEEN 3 AND 32)
);

CREATE TABLE characters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    name text NOT NULL,
    name_key text NOT NULL UNIQUE,
    breed smallint NOT NULL CHECK (breed BETWEEN 1 AND 19 AND breed <> 17),
    sex boolean NOT NULL,
    face smallint NOT NULL,
    hair smallint NOT NULL,
    colors jsonb NOT NULL CHECK (jsonb_typeof(colors) = 'array'),
    appearance jsonb NOT NULL CHECK (jsonb_typeof(appearance) = 'object'),
    level smallint NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 200),
    hp integer NOT NULL CHECK (hp >= 0),
    max_hp integer NOT NULL CHECK (max_hp > 0 AND hp <= max_hp),
    map_id integer NOT NULL DEFAULT 1134,
    instance_id bigint NOT NULL DEFAULT 0,
    x integer NOT NULL DEFAULT -12,
    y integer NOT NULL DEFAULT -8,
    z smallint NOT NULL DEFAULT -1,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (account_id, id)
);
CREATE INDEX characters_account ON characters(account_id);

CREATE TABLE sessions (
    account_id bigint PRIMARY KEY REFERENCES accounts(id),
    generation text NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    character_id bigint,
    FOREIGN KEY (account_id, character_id) REFERENCES characters(account_id, id)
);

CREATE TABLE tokens (
    digest text PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    kind text NOT NULL CHECK (kind IN ('game', 'remember', 'api', 'ticket', 'scheduler')),
    expires_at timestamptz NOT NULL,
    generation text,
    realm_id integer
);
CREATE INDEX tokens_expiry ON tokens(expires_at);

CREATE TABLE admin_role_audit (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    is_admin boolean NOT NULL,
    operator text NOT NULL CHECK (length(trim(operator)) > 0),
    reason text NOT NULL CHECK (length(trim(reason)) > 0),
    changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Immutable source bodies and verified index sets are shared independently.
-- Populated installations activate these through compact_native_storage.py.
CREATE TABLE native_catalog_bodies (
 body_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sha256 bytea NOT NULL UNIQUE CHECK(octet_length(sha256)=32),
 raw bytea NOT NULL,
 source_bytes bigint NOT NULL CHECK(source_bytes>=0),
 CHECK(octet_length(raw)=source_bytes AND pg_catalog.sha256(raw)=sha256)
);
CREATE TABLE native_catalog_index_sets (
 index_set_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 record_count integer NOT NULL DEFAULT 0 CHECK(record_count>=0),
 records_sha256 bytea CHECK(octet_length(records_sha256)=32),
 sealed boolean NOT NULL DEFAULT false,
 UNIQUE(records_sha256,record_count)
);
CREATE TABLE native_catalog_collections (
 collection_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE
);
CREATE TABLE native_catalog_index_records (
 index_set_id bigint NOT NULL REFERENCES native_catalog_index_sets(index_set_id) ON DELETE CASCADE,
 collection_id integer NOT NULL REFERENCES native_catalog_collections(collection_id),
 record_key text NOT NULL,
 payload jsonb NOT NULL,
 PRIMARY KEY(index_set_id,collection_id,record_key)
);
CREATE INDEX native_catalog_index_records_lookup
 ON native_catalog_index_records(collection_id,record_key,index_set_id);
CREATE TABLE native_catalog_document_links (
 revision text NOT NULL REFERENCES native_catalog_releases(revision),
 path text NOT NULL,
 body_id bigint NOT NULL REFERENCES native_catalog_bodies(body_id),
 index_set_id bigint NOT NULL REFERENCES native_catalog_index_sets(index_set_id),
 record_count integer NOT NULL CHECK(record_count>=0),
 PRIMARY KEY(revision,path)
);
CREATE INDEX native_catalog_document_links_body ON native_catalog_document_links(body_id);
CREATE INDEX native_catalog_document_links_index ON native_catalog_document_links(index_set_id);

CREATE FUNCTION guard_native_shared_body() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' AND current_setting('wakemu.native_catalog_maintenance',true)='on'
    AND NOT EXISTS(SELECT 1 FROM native_catalog_document_links WHERE body_id=OLD.body_id) THEN
  RETURN OLD;
 END IF;
 RAISE EXCEPTION 'A native source body is immutable';
END $$;
CREATE TRIGGER native_shared_body_immutable BEFORE UPDATE OR DELETE ON native_catalog_bodies
 FOR EACH ROW EXECUTE FUNCTION guard_native_shared_body();

CREATE FUNCTION guard_native_shared_index_set() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN
  IF current_setting('wakemu.native_catalog_maintenance',true)='on'
     AND NOT EXISTS(SELECT 1 FROM native_catalog_document_links WHERE index_set_id=OLD.index_set_id) THEN
   RETURN OLD;
  END IF;
  RAISE EXCEPTION 'Referenced native index sets cannot be deleted';
 END IF;
 IF OLD.sealed AND (NEW.index_set_id<>OLD.index_set_id OR NOT NEW.sealed OR NEW.record_count<>OLD.record_count
    OR (OLD.records_sha256 IS NOT NULL AND NEW.records_sha256 IS DISTINCT FROM OLD.records_sha256)) THEN
  RAISE EXCEPTION 'A sealed native index set is immutable';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER native_shared_index_set_immutable BEFORE UPDATE OR DELETE ON native_catalog_index_sets
 FOR EACH ROW EXECUTE FUNCTION guard_native_shared_index_set();

CREATE FUNCTION guard_native_shared_index_record() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE frozen boolean;
BEGIN
 IF TG_OP='DELETE' AND current_setting('wakemu.native_catalog_maintenance',true)='on'
    AND NOT EXISTS(SELECT 1 FROM native_catalog_document_links WHERE index_set_id=OLD.index_set_id) THEN
  RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' THEN
  SELECT bool_or(sealed) INTO frozen FROM native_catalog_index_sets
   WHERE index_set_id IN (OLD.index_set_id,NEW.index_set_id);
 ELSE
  SELECT sealed INTO frozen FROM native_catalog_index_sets
   WHERE index_set_id=CASE WHEN TG_OP='DELETE' THEN OLD.index_set_id ELSE NEW.index_set_id END;
 END IF;
 IF frozen THEN RAISE EXCEPTION 'Sealed native index records are immutable'; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER native_shared_index_record_immutable BEFORE INSERT OR UPDATE OR DELETE
 ON native_catalog_index_records FOR EACH ROW EXECUTE FUNCTION guard_native_shared_index_record();

CREATE FUNCTION native_shared_require_staging(selected_revision text,allow_retirement boolean DEFAULT false)
 RETURNS void LANGUAGE plpgsql AS $$
DECLARE published boolean;
BEGIN
 SELECT complete INTO published FROM native_catalog_releases WHERE revision=selected_revision FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Native release does not exist'; END IF;
 IF published AND NOT(allow_retirement AND current_setting('wakemu.native_catalog_maintenance',true)='on') THEN
  RAISE EXCEPTION 'Published native catalog is immutable';
 END IF;
END $$;

CREATE FUNCTION native_shared_mutable_set(selected_revision text,selected_path text,allow_retirement boolean DEFAULT false)
 RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE previous bigint; replacement bigint; frozen boolean;
BEGIN
 PERFORM native_shared_require_staging(selected_revision,allow_retirement);
 SELECT d.index_set_id,s.sealed INTO previous,frozen
 FROM native_catalog_document_links d JOIN native_catalog_index_sets s USING(index_set_id)
 WHERE d.revision=selected_revision AND d.path=selected_path FOR UPDATE OF d;
 IF previous IS NULL THEN RAISE EXCEPTION 'Native document does not exist'; END IF;
 DELETE FROM native_catalog_document_index_contracts
 WHERE revision=selected_revision AND path=selected_path;
 IF NOT frozen THEN RETURN previous; END IF;
 INSERT INTO native_catalog_index_sets DEFAULT VALUES RETURNING index_set_id INTO replacement;
 INSERT INTO native_catalog_index_records(index_set_id,collection_id,record_key,payload)
 SELECT replacement,collection_id,record_key,payload FROM native_catalog_index_records WHERE index_set_id=previous;
 UPDATE native_catalog_document_links SET index_set_id=replacement
 WHERE revision=selected_revision AND path=selected_path;
 RETURN replacement;
END $$;

CREATE FUNCTION write_native_shared_document() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE selected_body bigint; selected_set bigint;
BEGIN
 IF TG_RELID<>'native_catalog_documents'::regclass THEN
  RAISE EXCEPTION 'Native document writer requires its public view';
 END IF;
 IF NOT pg_try_advisory_xact_lock_shared(hashtextextended(
  current_database()||':'||TG_TABLE_SCHEMA||':native_catalog_maintenance',0)) THEN
  RAISE EXCEPTION 'Native catalog maintenance is in progress; retry the write' USING ERRCODE='40001';
 END IF;
 IF TG_OP='DELETE' THEN
  PERFORM native_shared_require_staging(OLD.revision,true);
  DELETE FROM native_catalog_document_links WHERE revision=OLD.revision AND path=OLD.path;
  RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' THEN PERFORM native_shared_require_staging(OLD.revision); END IF;
 PERFORM native_shared_require_staging(NEW.revision);
 IF NEW.sha256 !~ '^[0-9a-f]{64}$' OR NEW.source_bytes<>octet_length(NEW.raw)
    OR pg_catalog.sha256(NEW.raw)<>decode(NEW.sha256,'hex') THEN
  RAISE EXCEPTION 'Native document checksum/size mismatch';
 END IF;
 INSERT INTO native_catalog_bodies(sha256,raw,source_bytes)
 VALUES(decode(NEW.sha256,'hex'),NEW.raw,NEW.source_bytes) ON CONFLICT(sha256) DO NOTHING;
 SELECT body_id INTO selected_body FROM native_catalog_bodies
 WHERE sha256=decode(NEW.sha256,'hex') AND source_bytes=NEW.source_bytes;
 IF selected_body IS NULL THEN RAISE EXCEPTION 'Native source identity collision'; END IF;
 IF TG_OP='INSERT' THEN
  INSERT INTO native_catalog_index_sets DEFAULT VALUES RETURNING index_set_id INTO selected_set;
  INSERT INTO native_catalog_document_links(revision,path,body_id,index_set_id,record_count)
  VALUES(NEW.revision,NEW.path,selected_body,selected_set,NEW.record_count);
 ELSE
  IF NEW.sha256 IS DISTINCT FROM OLD.sha256 OR NEW.source_bytes IS DISTINCT FROM OLD.source_bytes
     OR NEW.record_count IS DISTINCT FROM OLD.record_count OR NEW.path IS DISTINCT FROM OLD.path
     OR NEW.revision IS DISTINCT FROM OLD.revision THEN
   DELETE FROM native_catalog_document_index_contracts WHERE revision=OLD.revision AND path=OLD.path;
  END IF;
  UPDATE native_catalog_document_links SET revision=NEW.revision,path=NEW.path,
   body_id=selected_body,record_count=NEW.record_count
  WHERE revision=OLD.revision AND path=OLD.path;
 END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION write_native_shared_record() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE selected_set bigint; selected_collection integer;
BEGIN
 IF TG_RELID<>'native_catalog_records'::regclass THEN
  RAISE EXCEPTION 'Native record writer requires its public view';
 END IF;
 IF NOT pg_try_advisory_xact_lock_shared(hashtextextended(
  current_database()||':'||TG_TABLE_SCHEMA||':native_catalog_maintenance',0)) THEN
  RAISE EXCEPTION 'Native catalog maintenance is in progress; retry the write' USING ERRCODE='40001';
 END IF;
 IF TG_OP IN ('DELETE','UPDATE') THEN
  selected_set=native_shared_mutable_set(OLD.revision,OLD.path,TG_OP='DELETE');
  DELETE FROM native_catalog_index_records r USING native_catalog_collections c
  WHERE r.collection_id=c.collection_id AND r.index_set_id=selected_set
   AND c.name=OLD.collection AND r.record_key=OLD.record_key;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 END IF;
 selected_set=native_shared_mutable_set(NEW.revision,NEW.path);
 INSERT INTO native_catalog_collections(name) VALUES(NEW.collection) ON CONFLICT(name) DO NOTHING;
 SELECT collection_id INTO selected_collection FROM native_catalog_collections WHERE name=NEW.collection;
 INSERT INTO native_catalog_index_records(index_set_id,collection_id,record_key,payload)
 VALUES(selected_set,selected_collection,NEW.record_key,NEW.payload);
 RETURN NEW;
END $$;

CREATE FUNCTION create_native_shared_catalog_views() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
 EXECUTE 'CREATE VIEW native_catalog_documents AS
  SELECT d.revision,d.path,b.raw,encode(b.sha256,''hex'') AS sha256,b.source_bytes,d.record_count
  FROM native_catalog_document_links d JOIN native_catalog_bodies b USING(body_id)';
 EXECUTE 'CREATE VIEW native_catalog_records AS
  SELECT d.revision,d.path,c.name AS collection,r.record_key,r.payload
  FROM native_catalog_document_links d JOIN native_catalog_index_records r USING(index_set_id)
  JOIN native_catalog_collections c USING(collection_id)';
 EXECUTE 'CREATE TRIGGER native_shared_document_writer INSTEAD OF INSERT OR UPDATE OR DELETE
  ON native_catalog_documents FOR EACH ROW EXECUTE FUNCTION write_native_shared_document()';
 EXECUTE 'CREATE TRIGGER native_shared_record_writer INSTEAD OF INSERT OR UPDATE OR DELETE
  ON native_catalog_records FOR EACH ROW EXECUTE FUNCTION write_native_shared_record()';
END $$;

CREATE FUNCTION seal_native_shared_release() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE selected record; actual integer;
BEGIN
 IF TG_RELID<>'native_catalog_releases'::regclass THEN
  RAISE EXCEPTION 'Native release seal requires its authority table';
 END IF;
 IF NOT pg_try_advisory_xact_lock_shared(hashtextextended(
  current_database()||':'||TG_TABLE_SCHEMA||':native_catalog_maintenance',0)) THEN
  RAISE EXCEPTION 'Native catalog maintenance is in progress; retry the write' USING ERRCODE='40001';
 END IF;
 IF TG_OP='UPDATE' THEN
  IF OLD.complete AND NOT NEW.complete AND EXISTS(
   SELECT 1 FROM native_catalog_document_links WHERE revision=OLD.revision) THEN
   RAISE EXCEPTION 'Published native catalog is immutable';
  END IF;
 END IF;
 IF NOT NEW.complete THEN RETURN NEW; END IF;
 -- Header-only archived provenance is complete even without resident payload.
 FOR selected IN SELECT DISTINCT d.index_set_id,s.sealed,s.record_count
 FROM native_catalog_document_links d JOIN native_catalog_index_sets s USING(index_set_id)
 WHERE d.revision=NEW.revision LOOP
  IF selected.sealed THEN actual=selected.record_count;
  ELSE
   SELECT count(*) INTO actual FROM native_catalog_index_records WHERE index_set_id=selected.index_set_id;
  END IF;
  IF EXISTS(SELECT 1 FROM native_catalog_document_links WHERE index_set_id=selected.index_set_id
            AND record_count<>actual) THEN RAISE EXCEPTION 'Native index count differs from document'; END IF;
  IF NOT selected.sealed THEN
   UPDATE native_catalog_index_sets SET record_count=actual,sealed=true WHERE index_set_id=selected.index_set_id;
  END IF;
 END LOOP;
 RETURN NEW;
END $$;
CREATE TRIGGER native_shared_release_seal BEFORE INSERT OR UPDATE ON native_catalog_releases
 FOR EACH ROW EXECUTE FUNCTION seal_native_shared_release();

-- Legacy roles retain their logical-view write grants, not direct pool access.
-- Fix the trusted schema before enabling definer trigger execution; pg_temp is
-- explicit and last so temporary objects cannot shadow the underlying tables.
DO $$
DECLARE selected text; trusted text=current_schema();
BEGIN
 FOREACH selected IN ARRAY ARRAY['write_native_shared_document','write_native_shared_record','seal_native_shared_release'] LOOP
  EXECUTE format('ALTER FUNCTION %I() SECURITY DEFINER',selected);
  EXECUTE format('ALTER FUNCTION %I() SET search_path TO pg_catalog,%I,pg_temp',selected,trusted);
 END LOOP;
END $$;

-- Pristine empty installations can switch immediately. Customized old schemas
-- use the explicit converter even when empty, preserving readers and access.
DO $$
DECLARE dependency record;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM native_catalog_documents LIMIT 1)
    AND NOT EXISTS(SELECT 1 FROM native_catalog_records LIMIT 1)
    AND NOT EXISTS(
     SELECT 1 FROM pg_class WHERE oid IN(
      'native_catalog_documents'::regclass,'native_catalog_records'::regclass)
     AND (relacl IS NOT NULL OR relowner<>(SELECT oid FROM pg_roles WHERE rolname=current_user)))
    AND NOT EXISTS(
     SELECT 1 FROM pg_attribute WHERE attrelid IN(
      'native_catalog_documents'::regclass,'native_catalog_records'::regclass)
      AND attacl IS NOT NULL)
    AND NOT EXISTS(
     SELECT 1 FROM pg_depend d JOIN pg_rewrite r
      ON r.oid=d.objid AND d.classid='pg_rewrite'::regclass
     WHERE d.refclassid='pg_class'::regclass AND d.refobjid IN(
      'native_catalog_documents'::regclass,'native_catalog_records'::regclass)
      AND r.ev_class<>d.refobjid)
    AND NOT EXISTS(
     SELECT 1 FROM pg_constraint WHERE contype='f' AND confrelid IN(
      'native_catalog_documents'::regclass,'native_catalog_records'::regclass)
      AND conrelid NOT IN('native_catalog_documents'::regclass,
       'native_catalog_records'::regclass,'native_catalog_document_index_contracts'::regclass)) THEN
  FOR dependency IN SELECT conname FROM pg_constraint
   WHERE conrelid='native_catalog_document_index_contracts'::regclass AND contype='f'
    AND confrelid='native_catalog_documents'::regclass LOOP
   EXECUTE format('ALTER TABLE native_catalog_document_index_contracts DROP CONSTRAINT %I',dependency.conname);
  END LOOP;
  DROP TABLE native_catalog_records;
  DROP TABLE native_catalog_documents;
  PERFORM create_native_shared_catalog_views();
  ALTER TABLE native_catalog_document_index_contracts ADD FOREIGN KEY(revision,path)
   REFERENCES native_catalog_document_links(revision,path);
 END IF;
END $$;

-- Explicit local emulator growth graph, not an official Wakfu schedule.
-- Plantable flora advances through catalog states in ascending order; state16
-- is excluded because it has no harvest actions. Every edge is editable in SQL.
-- Existing creation_time is the current stage entry time in milliseconds.
CREATE TABLE resource_growth_transitions (
    resource_reference integer NOT NULL CHECK(resource_reference > 0),
    from_stage smallint NOT NULL CHECK(from_stage BETWEEN 1 AND 127 AND from_stage <> 16),
    to_stage smallint NOT NULL CHECK(to_stage BETWEEN 1 AND 127 AND to_stage <> 16),
    delay_ms integer NOT NULL DEFAULT 30000 CHECK(delay_ms BETWEEN 1000 AND 86400000),
    CHECK(to_stage > from_stage),
    PRIMARY KEY(resource_reference,from_stage)
);
CREATE INDEX planted_resources_growth_stage
    ON planted_resources(resource_reference,stage,creation_time);

-- Local shop uses one authoritative account wallet for OG display and kamas.
CREATE TABLE shop_articles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key text NOT NULL UNIQUE,
    name text NOT NULL,
    description text NOT NULL DEFAULT '',
    item_ref integer NOT NULL CHECK(item_ref > 0),
    quantity integer NOT NULL DEFAULT 1 CHECK(quantity BETWEEN 1 AND 32767),
    price_kamas bigint NOT NULL DEFAULT 1000 CHECK(price_kamas > 0),
    category text NOT NULL DEFAULT 'items',
    enabled boolean NOT NULL DEFAULT true
);
CREATE TABLE shop_orders (
    id text PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    character_id bigint NOT NULL,
    request_key text NOT NULL CHECK(length(request_key) BETWEEN 1 AND 200),
    article_id bigint NOT NULL REFERENCES shop_articles(id),
    item_uid bigint NOT NULL,
    item_ref integer NOT NULL,
    quantity integer NOT NULL,
    price_kamas bigint NOT NULL CHECK(price_kamas > 0),
    balance bigint NOT NULL CHECK(balance >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    notified_at timestamptz,
    UNIQUE(account_id,request_key),
    FOREIGN KEY(account_id,character_id) REFERENCES characters(account_id,id)
);
CREATE INDEX shop_orders_pending ON shop_orders(account_id,character_id)
    WHERE notified_at IS NULL;

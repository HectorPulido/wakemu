-- Native titles and emotes use account ownership, independent of character presets.
CREATE TABLE native_title_learning_actions (
 item_ref integer PRIMARY KEY CHECK(item_ref>0),
 action_id integer NOT NULL CHECK(action_id>0),
 title_id integer NOT NULL CHECK(title_id BETWEEN 1 AND 65535),
 has_criteria boolean NOT NULL
);
CREATE TABLE title_learning_receipts (
 account_id bigint NOT NULL REFERENCES accounts(id),
 source_uid bigint NOT NULL,
 character_id bigint NOT NULL REFERENCES characters(id),
 source_ref integer NOT NULL,
 action_id integer NOT NULL,
 title_id integer NOT NULL,
 PRIMARY KEY(account_id,source_uid)
);
CREATE TABLE native_emote_learning_actions (
 item_ref integer PRIMARY KEY CHECK(item_ref>0),
 action_id integer NOT NULL CHECK(action_id>0),
 emote_id integer NOT NULL CHECK(emote_id>0),
 has_criteria boolean NOT NULL
);
CREATE TABLE native_emote_definitions (
 emote_id integer PRIMARY KEY CHECK(emote_id>0),
 unlock_default boolean NOT NULL DEFAULT true
);
CREATE TABLE account_emote_knowledge (
 account_id bigint NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
 emote_id integer NOT NULL CHECK(emote_id>0),
 learned_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(account_id,emote_id)
);
CREATE TABLE emote_learning_receipts (
 account_id bigint NOT NULL REFERENCES accounts(id),
 source_uid bigint NOT NULL,
 character_id bigint NOT NULL REFERENCES characters(id),
 source_ref integer NOT NULL,
 action_id integer NOT NULL,
 emote_id integer NOT NULL,
 PRIMARY KEY(account_id,source_uid)
);

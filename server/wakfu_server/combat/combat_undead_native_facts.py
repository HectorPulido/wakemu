# Original eVL.ST descriptors used by eXs for its evaluated eXt child.
_SYNTHETIC = ((-11, True), (-3, True), (-8, False), (-12, False))


@lru_cache(maxsize=1)
def _facts():
    known = zlib.decompress(base64.b85decode(_KNOWN_BITS))
    true = zlib.decompress(base64.b85decode(_TRUE_BITS))
    if len(known) != _BYTE_LENGTH or len(true) != _BYTE_LENGTH:
        raise ValueError("Invalid sealed native FKK bitset")
    return known, true


def original_fkk(reference):
    """Return the original native fact; reject foreign catalogues/unknown IDs."""
    from . import native_catalog

    if native_catalog.release() != NATIVE_CATALOG_REVISION:
        raise ValueError("Native FKK facts belong to another catalogue revision")
    if type(reference) is not int:
        raise ValueError("Native FKK requires an admitted integer effect reference")
    for synthetic, flag in _SYNTHETIC:
        if reference == synthetic:
            return flag
    if not 0 < reference <= _MAX_REFERENCE:
        raise ValueError("Unknown native FKK effect reference")
    known, true = _facts()
    index, bit = reference >> 3, 1 << (reference & 7)
    if not known[index] & bit:
        raise ValueError("Unknown native FKK effect reference")
    return bool(true[index] & bit)
